async (page) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('button', { name: '时间线 时间线', exact: true }).click();
  await page.getByRole('button', { name: '插件 插件', exact: true }).click();
  await page.getByRole('button', { name: '任务表 任务表', exact: true }).click();
  await page.getByRole('button', { name: '设置', exact: true }).first().click();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.settings-modal'));
  const result = await page.evaluate(async () => {
    const { closeLayer, enterPage } = await import('/src/motion.js');
    const check = (ok, message) => { if (!ok) throw new Error(message); };
    document.documentElement.dataset.uiMotion = 'full';
    const panel = document.createElement('div');
    panel.className = 'drawer';
    panel.textContent = 'animation fixture';
    document.body.append(panel);
    const entrance = panel.getAnimations()[0];
    check(entrance, 'drawer entrance absent');
    entrance.pause(); entrance.currentTime = 60;
    const before = { transform: getComputedStyle(panel).transform, opacity: getComputedStyle(panel).opacity };
    check(Number(before.opacity) < 1, 'fixture must close during entry');
    closeLayer(panel);
    const after = { transform: getComputedStyle(panel).transform, opacity: getComputedStyle(panel).opacity };
    check(before.transform === after.transform, 'closing transform jumped');
    check(Math.abs(Number(before.opacity) - Number(after.opacity)) < .01, 'closing opacity jumped');
    await new Promise(resolve => setTimeout(resolve, 360));
    check(!panel.isConnected, 'closing layer leaked');
    const host = document.createElement('div'); document.body.append(host);
    enterPage(host);
    const first = host.getAnimations()[0]; first.pause(); first.currentTime = 70;
    const midway = getComputedStyle(host).transform;
    enterPage(host, 'right');
    check(first.playState === 'idle', 'old page animation not cancelled');
    check(host.getAnimations().length === 1, 'page animations accumulated');
    check(getComputedStyle(host).transform === midway, 'interrupted page jumped');
    document.documentElement.dataset.uiMotion = 'reduced';
    enterPage(host);
    check(host.getAnimations().length === 0, 'reduced mode retained page animation');
    const quiet = document.createElement('div'); document.body.append(quiet);
    closeLayer(quiet); check(!quiet.isConnected, 'reduced mode must close immediately');
    host.remove(); delete document.documentElement.dataset.uiMotion;
    return { interruptedLayer: true, interruptedPage: true, reducedMotion: true };
  });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '显示或隐藏底栏', exact: true }).click();
  await page.getByRole('button', { name: '设置', exact: true }).first().click();
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.settings-modal'));
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('PASS: desktop navigation/settings, interrupted layer/page continuity, reduced motion, mobile settings; ' + JSON.stringify(result));
}
