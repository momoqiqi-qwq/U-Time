import assert from "node:assert/strict";
import { createPersistence } from "../src/persistence.js";
import { api } from "../src/api.js";
import * as S from "../src/store.js";

const memory = new Map();
globalThis.localStorage = { getItem: key => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value) };
memory.set("tidebalance-data", JSON.stringify({ tasks: [{ id: "legacy" }], blocks: [] }));
await S.initStore({});
assert.equal(S.getState().tasks[0].id, "legacy");
await S.saveNow();
assert.ok(memory.has("letime-data"));
assert.ok(memory.has("tidebalance-data"), "旧数据保留");
memory.set("letime-data", "broken");
await assert.rejects(S.initStore({ tasks: [], blocks: [] }));
assert.equal(S.getState(), null);
await assert.rejects(S.saveNow(), /禁止保存/);
assert.equal(memory.get("letime-data"), "broken", "读取失败不能覆盖原始内容");
memory.set("letime-data", "null");
await assert.rejects(S.initStore({}), /为空或损坏/);
memory.set("letime-data", JSON.stringify({ tasks: [], blocks: [], dataSchemaVersion: 99 }));
await assert.rejects(S.initStore({}), /更新版本/);
await assert.rejects(S.saveNow(), /禁止保存/);
memory.set("letime-data", JSON.stringify({ tasks: "bad", blocks: [] }));
await assert.rejects(S.initStore({}), /格式损坏/);
await api.recoverData({ tasks: [{ id: "restored" }], blocks: [] });
assert.ok([...memory.entries()].some(([key, value]) => key.startsWith("letime-data:recovery:") && value.includes('"bad"')));
await S.initStore({});
assert.equal(S.getState().tasks[0].id, "restored");

let current = { title: "first" }, release, fail = true;
const writes = [], phases = [];
const p = createPersistence({ snapshot: () => current, write: async data => {
  writes.push(data);
  if (fail) throw new Error("disk full");
  await new Promise(resolve => { release = resolve; });
}, delay: 10000 });
p.subscribe(s => phases.push(s.phase));
p.schedule(); await assert.rejects(p.flush(), /disk full/);
assert.equal(p.getStatus().phase, "error");
fail = false;
const pending = p.flush();
while (!release) await new Promise(resolve => setTimeout(resolve, 0));
current.title = "changed during write"; p.schedule();
assert.equal(writes.at(-1).title, "first", "写入中的快照不能被后续变更污染");
release(); await pending;
assert.equal(p.getStatus().phase, "pending", "旧快照回执不能把新变更标成已保存");
release = null;
const latest = p.flush();
while (!release) await new Promise(resolve => setTimeout(resolve, 0));
release(); await latest;
assert.equal(p.getStatus().phase, "saved");
assert.equal(writes.at(-1).title, "changed during write");
assert.ok(phases.includes("error") && phases.includes("saving"));
console.log("PASS: 读取失败保护、旧键迁移、原始副本、保存失败重试、串行快照与回执状态");
