import { readProductSource } from "./lib/read-product-source.mjs";
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read = p => readProductSource(new URL('../' + p, import.meta.url), 'utf8');
const source = read('src/views/settings/cppuLogin.js');
let state = { plugins: { 'cppu-notify': { enabled: false, storage: { loginRetries: 5, username: 'fixture', autoLogin: false } } } };
let saves = 0;
const el = (tag, props, ...children) => ({ tag, ...props, children, handlers: {}, addEventListener(event, fn) { this.handlers[event] = fn; } });
const context = vm.createContext({ el, toast() {}, S: { getState: () => state, pluginState(id) { return state.plugins[id] ||= { enabled: true, storage: {} }; }, persistSoon() { saves++; } } });
vm.runInContext(source.replace(/^import .+;$/gm, '').replaceAll('export ', '') + ';globalThis.cardApi = { createCppuLoginCard, normalizeLoginRetries };', context);
const { createCppuLoginCard, normalizeLoginRetries } = context.cardApi;
const card = createCppuLoginCard();
const select = card.children[1].children[1];
assert.equal(select.value, '5', 'existing retry preference is retained');
select.value = '0'; select.handlers.change();
assert.equal(state.plugins['cppu-notify'].storage.loginRetries, 0);
assert.equal(state.plugins['cppu-notify'].enabled, false, 'settings must not enable a disabled plugin');
assert.equal(state.plugins['cppu-notify'].storage.username, 'fixture');
assert.equal(state.plugins['cppu-notify'].storage.autoLogin, false);
assert.equal(saves, 1);
for (const value of [-1, 6, 1.5, 'invalid']) assert.equal(normalizeLoginRetries(value), 2);
state = { plugins: {} };
assert.equal(createCppuLoginCard().children[1].children[1].value, '2');
assert.deepEqual(state.plugins, {}, 'opening settings must not create or enable a plugin');
assert.match(read('src/views/settings.js'), /id: "cppu-login", create: \(\{ render \}\) => createCppuLoginCard\(\)/);
assert.match(read('public/plugins/cppu-notify/main.js'), /tide\.util\.openSettings\("cppu-login"\)/);
assert.doesNotMatch(read('public/plugins/cppu-notify/main.js'), /id: "cppu-login-settings"|data-login-retries/);
assert.match(read('src/pluginHost.js'), /openSettings:.*requirePermission.*"ui".*tide:open-settings/);
console.log('PASS: application login settings preserve retries and account state without registering a plugin view');
